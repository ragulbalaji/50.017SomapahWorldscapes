/* eslint-env browser */
import * as THREE from 'three'
import { PARAMETERS } from './config.js'
import { buildChunkGeometry } from './terrain/mesh.js'
import { worldToGrid, heightInGrid } from './terrain/ground.js'

// Chunk offsets within gen_depth of the player's chunk, nearest first.
const offsetsByDepth = new Map()
function offsetsWithin (depth) {
  let offsets = offsetsByDepth.get(depth)
  if (!offsets) {
    offsets = []
    for (let dx = -depth; dx <= depth; dx++) {
      for (let dz = -depth; dz <= depth; dz++) offsets.push([dx, dz])
    }
    offsets.sort((a, b) => (a[0] * a[0] + a[1] * a[1]) - (b[0] * b[0] + b[1] * b[1]))
    offsetsByDepth.set(depth, offsets)
  }
  return offsets
}

export class ChunkManager {
  constructor (scene, material, decorations) {
    this.scene = scene
    this.material = material
    this.decorations = decorations
    this.entries = new Map() // 'cx,cz' -> { cx, cz, mesh, heights, decorations }
    this.changed = false // chunks added or removed since the last decoration rebuild
    this.epoch = 0 // bumped by reset(); results from older epochs are dropped
    this.pending = new Set() // keys being generated by a worker
    this.failed = new Set() // keys whose worker crashed; not retried until reset()
    this.pcx = 0 // player chunk at the last update()
    this.pcz = 0
    const poolSize = Math.max(1, Math.min(4, (navigator.hardwareConcurrency || 4) - 1))
    this.slots = []
    for (let i = 0; i < poolSize; i++) {
      const slot = {
        worker: new Worker(new URL('./terrain/worker.js', import.meta.url), { type: 'module' }),
        jobKey: null,
        jobEpoch: 0
      }
      slot.worker.onmessage = ({ data }) => this.onResult(slot, data)
      slot.worker.onerror = (event) => this.onWorkerError(slot, event)
      this.slots.push(slot)
    }
  }

  get size () {
    return this.entries.size
  }

  update (position) {
    const cs = PARAMETERS.chunk_size
    const depth = PARAMETERS.gen_depth
    const pcx = Math.floor(position.x / cs + 0.5)
    const pcz = Math.floor(position.z / cs + 0.5)
    this.pcx = pcx
    this.pcz = pcz

    for (const [key, entry] of this.entries) {
      if (Math.max(Math.abs(entry.cx - pcx), Math.abs(entry.cz - pcz)) > depth + 1) this.unload(key)
    }

    // Give the nearest missing chunks to the idle workers, one job each.
    const idle = this.slots.filter(slot => slot.jobKey === null)
    for (const [dx, dz] of offsetsWithin(depth)) {
      if (idle.length === 0) break
      const cx = pcx + dx
      const cz = pcz + dz
      const key = `${cx},${cz}`
      if (this.entries.has(key) || this.pending.has(key) || this.failed.has(key)) continue
      const slot = idle.pop()
      slot.worker.postMessage({ epoch: this.epoch, key, cx, cz, params: { ...PARAMETERS } })
      slot.jobKey = key
      slot.jobEpoch = this.epoch
      this.pending.add(key)
    }

    if (this.changed) {
      this.changed = false
      const nearest = [...this.entries.values()].sort((a, b) =>
        ((a.cx - pcx) ** 2 + (a.cz - pcz) ** 2) - ((b.cx - pcx) ** 2 + (b.cz - pcz) ** 2))
      this.decorations.rebuild(nearest)
    }
  }

  onResult (slot, { epoch, key, cx, cz, ...chunk }) {
    slot.jobKey = null
    if (epoch !== this.epoch) return // reset() already cleared pending; the key may be pending again
    this.pending.delete(key)
    if (Math.max(Math.abs(cx - this.pcx), Math.abs(cz - this.pcz)) > PARAMETERS.gen_depth + 1) return
    if (Math.round(Math.sqrt(chunk.heights.length)) !== PARAMETERS.chunk_size) return
    if (this.entries.has(key)) return
    this.add(key, cx, cz, chunk)
  }

  onWorkerError (slot, event) {
    console.error('Chunk worker failed', slot.jobKey, event.message)
    event.preventDefault()
    if (slot.jobEpoch === this.epoch) {
      this.failed.add(slot.jobKey)
      this.pending.delete(slot.jobKey)
    }
    slot.jobKey = null
  }

  add (key, cx, cz, { heights, uvs, decorations }) {
    const cs = PARAMETERS.chunk_size
    const mesh = new THREE.Mesh(buildChunkGeometry(cs, heights, uvs), this.material)
    mesh.position.set(cx * cs, 0, cz * cs)
    mesh.castShadow = true
    mesh.receiveShadow = true
    this.scene.add(mesh)
    this.entries.set(key, { cx, cz, mesh, heights, decorations })
    this.changed = true
  }

  unload (key) {
    const { mesh } = this.entries.get(key)
    mesh.geometry.dispose()
    this.scene.remove(mesh)
    this.entries.delete(key)
    this.changed = true
  }

  // Height of the rendered terrain at world (x, z); null if that chunk is not loaded.
  groundHeightAt (x, z) {
    const cs = PARAMETERS.chunk_size
    const gx = worldToGrid(x, cs)
    const gz = worldToGrid(z, cs)
    const entry = this.entries.get(`${gx.c},${gz.c}`)
    return entry ? heightInGrid(entry.heights, cs, gx.g, gz.g) : null
  }

  setMaterial (material) {
    this.material = material
    for (const { mesh } of this.entries.values()) mesh.material = material
  }

  reset () {
    for (const key of this.entries.keys()) this.unload(key)
    this.epoch++
    this.pending.clear()
    this.failed.clear()
  }
}
